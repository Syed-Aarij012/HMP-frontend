export default function ListingDetailActionIcons({
  car,
}: ListingDetailActionIconsProps) {
  const { isFavorite, addToCompare, toggleFavorite } = useListingActions();
  const [copied, setCopied] = useState(false);

  const favoriteActive = isFavorite(car.id);

  const handleShare = async () => {
    const url = typeof window !== "undefined" ? window.location.href : "";
    const shareData = { title: car.title, url };

    if (typeof navigator !== "undefined" && navigator.share) {
      try {
        await navigator.share(shareData);
        return;
      } catch {
        // User cancelled the share sheet, or the browser rejected it — fall through
        // to copy-link so the button still does something useful.
      }
    }

    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard access denied — nothing more we can do without a visible text field.
    }
  };

  const handlePrint = () => {
    if (typeof window !== "undefined") {
      window.print();
    }
  };

  return (
    <>
      <li>
        <button
          type="button"
          className="icon"
          onClick={() => toggleFavorite(car)}
          aria-label={
            favoriteActive ? "Remove from favorites" : "Add to favorites"
          }
          aria-pressed={favoriteActive}
        >
          {favoriteActive ? (
            <i className="icon-carus-trashsimple" />
          ) : (
            <HeartIcon />
          )}
        </button>
      </li>
      <li>
        <a
          href="#"
          data-bs-toggle="offcanvas"
          data-bs-target="#offcanvasBottom"
          aria-controls="offcanvasBottom"
          className="icon"
          onClick={(event) => {
            event.preventDefault();
            addToCompare(car);
          }}
          aria-label="Add to compare"
        >
          <CompareIcon />
        </a>
      </li>
      <li>
        <button
          type="button"
          className="icon"
          onClick={handleShare}
          aria-label={copied ? "Link copied" : "Share this listing"}
          title={copied ? "Link copied!" : "Share this listing"}
        >
          {copied ? <CheckIcon /> : <ShareIcon />}
        </button>
      </li>
      <li>
        <button
          type="button"
          className="icon"
          onClick={handlePrint}
          aria-label="Print this listing"
          title="Print this listing"
        >
          <PrinterIcon />
        </button>
      </li>
    </>
  );
}
