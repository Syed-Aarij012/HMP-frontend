function formatDashboardPostingDate(date: Date) {
  return date.toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });
}

function getRecentPostingDate(seed: number, maxDaysAgo = 90) {
  const today = new Date(2026, 6, 1);
  const daysAgo = (seed * 13 + seed * seed * 3 + 5) % maxDaysAgo;
  const date = new Date(today);

  date.setDate(date.getDate() - daysAgo);

  return formatDashboardPostingDate(date);
}

function createDashboardCar(
  id: number,
  dashboardImage: string,
  title: string,
  dashboardStatus: DashboardListingStatus,
  overrides?: Partial<DashboardCar>,
): DashboardCar {
  return {
    id,
    image:
      overrides?.image ??
      `/assets/images/car-list/car${((id - 1) % 6) + 24}.webp`,
    dashboardImage,
    title,
    price: 73000,
    mileage: 1032,
    transmission: "Auto",
    fuel: "Petrol",
    tag: "New",
    photoCount: 6,
    description: DASHBOARD_LISTING_DESCRIPTION,
    dashboardStatus,
    postingDate: getRecentPostingDate(id),
    href: `/listing-detail-v1/${id}`,
    ...overrides,
  };
}

