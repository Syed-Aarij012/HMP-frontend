export function getCarById(id: number): Car | undefined {
  return allCars.find((car) => car.id === id);
}

export function getCarDetailTitle(id: number): string {
  return getCarById(id)?.title ?? DEFAULT_LISTING_DETAIL_TITLE;
}

export function getCarDetailHref(
  id: number,
  variant: ListingDetailVariant = "v1",
): string {
  return `/listing-detail-${variant}/${id}`;
}

export function getCarHref(
  car: Pick<Car, "id" | "href">,
  variant: ListingDetailVariant = "v1",
): string {
  return car.href ?? getCarDetailHref(car.id, variant);
}
